/* =============================================================================
   OUTINGS — where to go on a day off, and what it costs to get there.

   WHY THIS FILE EXISTS AND IS NOT IN data.js
   A culture post is a dated item in a feed with a body of HTML. An outing is a
   small, structured record: a photograph, a route, a price, and two or three
   practical warnings. Putting them in the posts table would mean a schema that
   can only hold prose, and a route rendered as a paragraph is the one thing a
   helper standing at the wrong bus stop cannot use.

   So this is static data, shipped with the code, loaded by /places.js. No table,
   no admin screen, no migration. A place is added by editing this array.

   WHAT IS TRANSLATED, AND WHAT IS NOT
   The chrome (labels, filters, "how to get there", every transport sentence) is
   translated into all four learner languages, because that is navigation.
   `summary` is translated too, because it is the text on the card and she has to
   be able to decide from it. `goodToKnow` is ENGLISH ONLY, the same rule the
   Living passages and the news feed already follow: prose that a reader can
   skim is not worth a machine translation, and a wrong machine translation of a
   safety warning is worse than an English one. `name` is a proper noun and stays
   as it is, with the Chinese name beside it — she will see the Chinese name on
   the sign at the station, not the English one.

   PRICES
   Checked in October 2026 against the operators' own published fares (Star
   Ferry, the Transport Department's licensed-ferry tables for the outlying
   islands). Fares change, and the ones marked `approx` are the ones the
   operator does not publish in a form that can be quoted exactly — the page
   says so rather than pretending to a precision it does not have. Every paid
   card says what the money is FOR, because "HK$88" with no object is not a
   price, it is a number.

   PHOTOGRAPHS
   Every photograph is a Wikimedia Commons file under a free licence, and each
   one is credited on its page by author and licence. `public/places/credits.json`
   is generated by `tools/fetch-place-photos.js` at the same moment the file is
   downloaded, so the credit cannot drift from the image it describes.
   =========================================================================== */

